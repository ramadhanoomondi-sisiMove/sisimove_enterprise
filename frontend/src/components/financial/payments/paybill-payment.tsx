// -----------------------------------------------------------------------------
// sisiMove — PayBill Payment
// -----------------------------------------------------------------------------
//
// Dedicated presentation for an already-created C2B FinancialPayment.
//
// Responsibilities:
// - Present the configured PayBill number and payment-specific C2B reference.
// - Show the amount using the shared minor-unit financial formatter.
// - Explain the manual M-PESA PayBill steps.
// - Let the member copy the PayBill number and account reference.
// - Let the member confirm that they have paid, triggering backend
//   reconciliation for this existing payment.
// - Let the member refresh the status of this existing payment.
//
// Architectural boundary:
// - This component does not create payments.
// - This component does not generate payment references.
// - This component does not process M-PESA callbacks or credit wallets.
// - onIHavePaid requests backend reconciliation; it is not proof of payment.
// - onCheckStatus refreshes the existing payment only.
//
// -----------------------------------------------------------------------------

'use client';

import { useState } from 'react';
import {
  Check,
  Clipboard,
  Clock3,
  Copy,
  Loader2,
  RefreshCw,
} from 'lucide-react';

import { Button } from '@/components/ui/button';

import { FinancialAmount } from '../shared/financial-amount';
import {
  FinancialStatusBadge,
  type FinancialStatusTone,
} from '../shared/financial-status-badge';

// -----------------------------------------------------------------------------
// Types
// -----------------------------------------------------------------------------

export type PayBillPaymentStatus =
  | 'PENDING'
  | 'PROCESSING'
  | 'COMPLETED'
  | 'FAILED'
  | 'CANCELLED'
  | 'EXPIRED';

export interface PayBillPaymentProps {
  /** Existing payment's public identifier. Used for context, not creation. */
  paymentPublicId: string;

  /** Configured SisiMove PayBill shortcode. */
  paybillNumber: string;

  /** Unique account reference already generated by the backend. */
  c2bReference: string;

  /** Amount expressed in integer minor units. */
  amount: number;

  /** ISO currency code. */
  currency?: string;

  /** Current status of the existing FinancialPayment. */
  status: PayBillPaymentStatus;

  /** Optional additional instructions supplied by the payment provider. */
  instructions?: string[];

  /**
   * Requests reconciliation of this existing C2B payment.
   * The backend remains authoritative about whether payment was received.
   */
  onIHavePaid: () => void | Promise<void>;

  /** True while the reconciliation mutation is running. */
  isReconciling?: boolean;

  /** Optional error returned by the latest reconciliation request. */
  reconciliationError?: string | null;

  /** Optional message returned by the backend reconciliation workflow. */
  reconciliationMessage?: string | null;

  /**
   * Refresh/check the status of this existing payment.
   * Must not create a new FinancialPayment.
   */
  onCheckStatus: () => void | Promise<void>;

  /** True while the parent is fetching the latest payment status. */
  isCheckingStatus?: boolean;

  /** Optional error returned by the latest status check. */
  statusCheckError?: string | null;

  /** Optional callback when the member chooses to leave this screen. */
  onBack?: () => void;

  /** Optional class name for page/container composition. */
  className?: string;
}

// -----------------------------------------------------------------------------
// Status presentation
// -----------------------------------------------------------------------------

const STATUS_PRESENTATION: Record<
  PayBillPaymentStatus,
  { label: string; tone: FinancialStatusTone; message: string }
> = {
  PENDING: {
    label: 'Awaiting payment',
    tone: 'warning',
    message:
      'Complete the M-PESA payment using the details below. Your wallet is credited only after sisiMove receives and confirms the payment.',
  },
  PROCESSING: {
    label: 'Processing',
    tone: 'brand',
    message:
      'M-PESA has reported activity for this payment. sisiMove is processing the confirmation. Please check again shortly.',
  },
  COMPLETED: {
    label: 'Payment received',
    tone: 'success',
    message:
      'Your payment has been confirmed. Your sisiMove wallet should reflect the credited amount.',
  },
  FAILED: {
    label: 'Payment failed',
    tone: 'danger',
    message:
      'This payment was not completed. Please review the status before attempting another top-up.',
  },
  CANCELLED: {
    label: 'Payment cancelled',
    tone: 'neutral',
    message: 'This payment was cancelled and can no longer be used.',
  },
  EXPIRED: {
    label: 'Payment expired',
    tone: 'neutral',
    message:
      'This payment reference has expired. Return to the top-up form to create a new payment if you still wish to add funds.',
  },
};

const DEFAULT_INSTRUCTIONS = [
  'Open M-PESA on your phone.',
  'Select Lipa na M-PESA, then Pay Bill.',
  'Enter the PayBill number shown below.',
  'Enter the unique account reference shown below.',
  'Enter the exact amount shown below and confirm the payment.',
];

// -----------------------------------------------------------------------------
// Copy control
// -----------------------------------------------------------------------------

interface CopyValueProps {
  label: string;
  value: string;
}

function CopyValue({ label, value }: CopyValueProps) {
  const [copied, setCopied] = useState(false);
  const [copyError, setCopyError] = useState<string | null>(null);

  async function handleCopy() {
    setCopyError(null);

    try {
      await navigator.clipboard.writeText(value);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1800);
    } catch {
      setCopied(false);
      setCopyError(
        'Copy is unavailable. Please select and copy the value manually.',
      );
    }
  }

  return (
    <div className="flex min-w-0 items-center justify-between gap-3">
      <div className="min-w-0">
        <p className="text-xs text-[var(--foreground-muted)]">{label}</p>
        <p className="break-all text-lg font-semibold tracking-wide text-[var(--foreground)]">
          {value}
        </p>
      </div>

      <Button
        type="button"
        variant="outline"
        size="sm"
        onClick={handleCopy}
        aria-label={`Copy ${label.toLowerCase()}`}
        leadingIcon={
          copied ? <Check className="h-4 w-4" /> : <Copy className="h-4 w-4" />
        }
      >
        {copied ? 'Copied' : 'Copy'}
      </Button>

      {copyError ? (
        <span role="alert" className="sr-only">
          {copyError}
        </span>
      ) : null}
    </div>
  );
}

// -----------------------------------------------------------------------------
// Component
// -----------------------------------------------------------------------------

export function PayBillPayment({
  paymentPublicId,
  paybillNumber,
  c2bReference,
  amount,
  currency = 'KES',
  status,
  instructions,
  onIHavePaid,
  isReconciling = false,
  reconciliationError,
  reconciliationMessage,
  onCheckStatus,
  isCheckingStatus = false,
  statusCheckError,
  onBack,
  className,
}: PayBillPaymentProps) {
  const presentation = STATUS_PRESENTATION[status];

  const isTerminal =
    status === 'COMPLETED' ||
    status === 'FAILED' ||
    status === 'CANCELLED' ||
    status === 'EXPIRED';

  const canReconcile = status === 'PENDING';

  const steps = instructions?.length ? instructions : DEFAULT_INSTRUCTIONS;

  return (
    <section
      aria-labelledby="paybill-payment-title"
      className={['mx-auto w-full max-w-2xl space-y-5', className]
        .filter(Boolean)
        .join(' ')}
    >
      <header className="space-y-2">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <p className="text-xs font-semibold uppercase tracking-wider text-[var(--foreground-muted)]">
            sisiMove wallet
          </p>

          <FinancialStatusBadge
            label={presentation.label}
            tone={presentation.tone}
          />
        </div>

        <h1
          id="paybill-payment-title"
          className="text-2xl font-semibold tracking-tight text-[var(--foreground)]"
        >
          Pay using M-PESA PayBill
        </h1>

        <p className="text-sm leading-6 text-[var(--foreground-muted)]">
          Use the payment details below to add money to your sisiMove wallet.
          This reference belongs to this payment only.
        </p>
      </header>

      <div className="rounded-xl border border-[var(--border)] bg-[var(--surface)] p-4 sm:p-5">
        <div className="space-y-1">
          <p className="text-xs font-medium uppercase tracking-wide text-[var(--foreground-muted)]">
            Amount to pay
          </p>

          <FinancialAmount
            amount={amount}
            currency={currency}
            className="block text-3xl font-bold"
          />
        </div>

        <div className="my-5 border-t border-[var(--border)]" />

        <div className="space-y-5">
          <CopyValue label="PayBill number" value={paybillNumber} />

          <div className="border-t border-dashed border-[var(--border)]" />

          <CopyValue
            label="Your unique account reference"
            value={c2bReference}
          />
        </div>
      </div>

      <div className="rounded-xl border border-[var(--border)] bg-[var(--surface)] p-4 sm:p-5">
        <h2 className="text-base font-semibold text-[var(--foreground)]">
          How to pay
        </h2>

        <ol className="mt-3 list-decimal space-y-2 pl-5 text-sm leading-6 text-[var(--foreground-muted)]">
          {steps.map((step, index) => (
            <li key={`${index}-${step}`}>{step}</li>
          ))}
        </ol>

        <p className="mt-4 text-xs leading-5 text-[var(--foreground-muted)]">
          Enter the account reference exactly as shown. Your wallet is updated
          only after sisiMove receives, validates, and processes the M-PESA
          confirmation.
        </p>
      </div>

      <div
        className="rounded-xl border border-[var(--border)] bg-[var(--background-subtle)] p-4"
        aria-live="polite"
      >
        <div className="flex items-start gap-3">
          {status === 'COMPLETED' ? (
            <Check className="mt-0.5 h-5 w-5 shrink-0 text-[var(--success)]" />
          ) : status === 'PROCESSING' ? (
            <Loader2 className="mt-0.5 h-5 w-5 shrink-0 animate-spin text-[var(--brand)]" />
          ) : status === 'PENDING' ? (
            <Clock3 className="mt-0.5 h-5 w-5 shrink-0 text-[var(--warning)]" />
          ) : (
            <Clipboard className="mt-0.5 h-5 w-5 shrink-0 text-[var(--foreground-muted)]" />
          )}

          <div className="min-w-0 flex-1 space-y-1">
            <p className="text-sm font-semibold text-[var(--foreground)]">
              {presentation.label}
            </p>

            <p className="text-sm leading-6 text-[var(--foreground-muted)]">
              {presentation.message}
            </p>
          </div>
        </div>

        {reconciliationMessage ? (
          <p
            role="status"
            className="mt-3 rounded-lg border border-[var(--border)] p-3 text-sm text-[var(--foreground)]"
          >
            {reconciliationMessage}
          </p>
        ) : null}

        {reconciliationError ? (
          <p
            role="alert"
            className="mt-3 rounded-lg border border-[var(--danger)]/30 bg-[var(--danger-soft)] p-3 text-sm text-[var(--danger)]"
          >
            {reconciliationError}
          </p>
        ) : null}

        {statusCheckError ? (
          <p
            role="alert"
            className="mt-3 rounded-lg border border-[var(--danger)]/30 bg-[var(--danger-soft)] p-3 text-sm text-[var(--danger)]"
          >
            {statusCheckError}
          </p>
        ) : null}

        {canReconcile ? (
          <Button
            type="button"
            variant="primary"
            size="lg"
            className="mt-4 w-full"
            loading={isReconciling}
            disabled={isReconciling}
            onClick={() => void onIHavePaid()}
          >
            I have paid
          </Button>
        ) : null}

        {!isTerminal ? (
          <Button
            type="button"
            variant="outline"
            size="md"
            className="mt-3 w-full"
            loading={isCheckingStatus}
            disabled={isCheckingStatus || isReconciling}
            leadingIcon={!isCheckingStatus ? <RefreshCw className="h-4 w-4" /> : undefined}
            onClick={() => void onCheckStatus()}
          >
            Check payment status
          </Button>
        ) : null}

        {onBack && status !== 'COMPLETED' ? (
          <Button
            type="button"
            variant="ghost"
            size="md"
            className="mt-3 w-full"
            onClick={onBack}
          >
            Back to top up
          </Button>
        ) : null}
      </div>

      <p className="text-center text-xs text-[var(--foreground-muted)]">
        Payment reference:{' '}
        <span className="font-medium">{paymentPublicId}</span>
      </p>
    </section>
  );
}

export default PayBillPayment;
