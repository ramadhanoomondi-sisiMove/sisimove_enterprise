// -----------------------------------------------------------------------------
// Journey Boarding — Cancel Request DTO
// -----------------------------------------------------------------------------

import { ApiPropertyOptional } from '@nestjs/swagger';

import {
  IsDateString,
  IsOptional,
  IsString,
  MaxLength,
  MinLength,
} from 'class-validator';

/**
 * REST request DTO for cancelling a Journey Boarding.
 *
 * The Journey Boarding public identifier comes from the route parameter.
 * The authenticated identity supplies the cancellation actor.
 * Correlation metadata is generated by the backend.
 *
 * This DTO contains transport primitives only.
 * The presentation/application mapping layer converts cancelledAt into a Date
 * before constructing CancelJourneyBoardingCommand.
 */
export class CancelJourneyBoardingDto {
  // ===========================================================================
  // Causation
  // ===========================================================================

  /**
   * Optional identifier of the command or event that caused this request.
   */
  @ApiPropertyOptional({
    description: 'Identifier of the command or event that caused this request.',
    example: 'cmd-01J8XYZABC',
    minLength: 1,
    maxLength: 200,
  })
  @IsOptional()
  @IsString()
  @MinLength(1)
  @MaxLength(200)
  causationId?: string;

  // ===========================================================================
  // Cancellation Timestamp
  // ===========================================================================

  /**
   * Optional timestamp at which the Journey Boarding was cancelled.
   *
   * When omitted, the domain uses the current time.
   */
  @ApiPropertyOptional({
    description:
      'ISO-8601 timestamp representing when the Journey Boarding was cancelled.',
    example: '2026-08-19T10:50:00.000Z',
    format: 'date-time',
  })
  @IsOptional()
  @IsDateString()
  cancelledAt?: string;
}

// -----------------------------------------------------------------------------
// Default Export
// -----------------------------------------------------------------------------

export default CancelJourneyBoardingDto;
