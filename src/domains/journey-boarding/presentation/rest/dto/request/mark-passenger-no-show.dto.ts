// -----------------------------------------------------------------------------
// Journey Boarding — Mark Passenger No-Show Request DTO
// -----------------------------------------------------------------------------

import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

import {
  IsDateString,
  IsOptional,
  IsString,
  MaxLength,
  MinLength,
} from 'class-validator';

/**
 * REST request DTO for marking a passenger as a no-show.
 *
 * The Journey Boarding public identifier comes from the route parameter.
 * Correlation metadata is generated by the backend.
 *
 * This DTO contains transport primitives only.
 * The presentation/application mapping layer converts participantPublicId
 * into the corresponding domain value object and noShowAt into a Date.
 */
export class MarkPassengerNoShowDto {
  // ===========================================================================
  // Participant
  // ===========================================================================

  @ApiProperty({
    description:
      'Public identifier of the passenger participant being marked as a no-show.',
    example: 'JBP-01J8XYZ456',
    minLength: 1,
    maxLength: 100,
  })
  @IsString()
  @MinLength(1)
  @MaxLength(100)
  participantPublicId!: string;

  // ===========================================================================
  // Causation
  // ===========================================================================

  @ApiPropertyOptional({
    description:
      'Identifier of the command or event that caused this request, when applicable.',
    example: 'cmd-01J8XYZABC',
    minLength: 1,
    maxLength: 200,
  })
  @IsOptional()
  @IsString()
  @MinLength(1)
  @MaxLength(200)
  causationId?: string;

  // ===========================================================================
  // No-Show Time
  // ===========================================================================

  @ApiPropertyOptional({
    description:
      'ISO-8601 timestamp representing when the passenger was determined to be a no-show. Defaults to the current time when omitted.',
    example: '2026-08-19T07:00:00.000Z',
    format: 'date-time',
  })
  @IsOptional()
  @IsDateString()
  noShowAt?: string;
}

export default MarkPassengerNoShowDto;
