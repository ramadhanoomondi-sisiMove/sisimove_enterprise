// -----------------------------------------------------------------------------
// Journey Boarding — Remove Participant Request DTO
// -----------------------------------------------------------------------------

import { ApiPropertyOptional } from '@nestjs/swagger';

import {
  IsDateString,
  IsOptional,
  IsString,
  MaxLength,
  MinLength,
} from 'class-validator';

/**
 * REST request DTO for removing a Journey Boarding participant.
 *
 * The Journey Boarding and participant public identifiers are resolved
 * outside this request body.
 * The authenticated identity supplies the actor.
 * Correlation metadata is generated by the backend.
 *
 * This DTO contains only optional request metadata supplied by the frontend.
 * The presentation/application mapping layer converts removedAt into a Date.
 */
export class RemoveParticipantDto {
  // ===========================================================================
  // Causation
  // ===========================================================================

  @ApiPropertyOptional({
    description:
      'Identifier of the command or event that caused this request, when applicable.',
    example: 'cmd-01J8XYZDEF',
    minLength: 1,
    maxLength: 200,
  })
  @IsOptional()
  @IsString()
  @MinLength(1)
  @MaxLength(200)
  causationId?: string;

  // ===========================================================================
  // Removal Timestamp
  // ===========================================================================

  @ApiPropertyOptional({
    description:
      'Optional ISO-8601 timestamp representing when the participant was removed.',
    example: '2026-08-19T10:30:00.000Z',
    format: 'date-time',
  })
  @IsOptional()
  @IsDateString()
  removedAt?: string;
}

export default RemoveParticipantDto;
