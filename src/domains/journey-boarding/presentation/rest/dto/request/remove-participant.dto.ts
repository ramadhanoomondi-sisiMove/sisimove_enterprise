// -----------------------------------------------------------------------------
// Journey Boarding — Remove Participant Request DTO
// -----------------------------------------------------------------------------

import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

import {
  IsDateString,
  IsOptional,
  IsString,
  MaxLength,
  MinLength,
} from 'class-validator';

/**
 * REST request DTO for removing a Journey Boarding participant.
 *
 * The Journey Boarding public identifier comes from the route parameter.
 * The authenticated identity supplies the actor.
 * Correlation metadata is generated by the backend.
 *
 * This DTO contains transport primitives only.
 * The presentation/application mapping layer converts participantPublicId
 * into the corresponding domain value object and removedAt into a Date.
 */
export class RemoveParticipantDto {
  // ===========================================================================
  // Participant
  // ===========================================================================

  @ApiProperty({
    description:
      'Public identifier of the Journey Boarding participant being removed.',
    example: 'JBP-01J8XYZ456',
    minLength: 1,
    maxLength: 100,
  })
  @IsString()
  @MinLength(1)
  @MaxLength(100)
  participantPublicId!: string;

  // ===========================================================================
  // Causation
  // ===========================================================================

  @ApiPropertyOptional({
    description:
      'Identifier of the command or event that caused this request, when applicable.',
    example: 'cmd-01J8XYZDEF',
    minLength: 1,
    maxLength: 200,
  })
  @IsOptional()
  @IsString()
  @MinLength(1)
  @MaxLength(200)
  causationId?: string;

  // ===========================================================================
  // Removal Timestamp
  // ===========================================================================

  @ApiPropertyOptional({
    description:
      'Optional ISO-8601 timestamp representing when the participant was removed.',
    example: '2026-08-19T10:30:00.000Z',
    format: 'date-time',
  })
  @IsOptional()
  @IsDateString()
  removedAt?: string;
}

export default RemoveParticipantDto;
