/**
 * Safaricom Daraja 3.0 — M-PESA B2C Payment Request
 *
 * Request payload for:
 * POST /mpesa/b2c/v3/paymentrequest
 *
 * Based on Safaricom's official Daraja B2C documentation.
 *
 * This interface describes the provider transport payload only.
 * It must not contain consumer keys, consumer secrets, or
 * plaintext initiator passwords.
 *
 * SisiMove B2C scope:
 * - Journey earnings
 * - Commissions
 * - Settlements
 *
 * Employee salaries and promotional payments are excluded.
 * The specific business payout classification is retained
 * separately in SisiMove's domain metadata.
 */

// =============================================================================
// Command ID
// =============================================================================

/**
 * SisiMove uses BusinessPayment for all supported business
 * disbursements in this workflow.
 */
export type MpesaB2CCommandId = 'BusinessPayment';

// =============================================================================
// Request
// =============================================================================

export interface MpesaB2CRequest {
  /**
   * Unique identifier generated by SisiMove for every B2C request.
   * Persist this before submission to prevent duplicate disbursements.
   */
  OriginatorConversationID: string;

  /** Daraja API initiator username. */
  InitiatorName: string;

  /**
   * Safaricom-encrypted initiator credential.
   * Never use the plaintext initiator password.
   */
  SecurityCredential: string;

  /** B2C command used for SisiMove business payouts. */
  CommandID: MpesaB2CCommandId;

  /** Amount in KES. Must be a positive whole number. */
  Amount: number;

  /** Organization B2C shortcode from which funds are disbursed. */
  PartyA: string;

  /**
   * Recipient MSISDN in international format without a plus sign.
   * Example: 2547XXXXXXXX
   */
  PartyB: string;

  /** Transaction description (2–100 characters). */
  Remarks: string;

  /** Public HTTPS endpoint for queue-timeout notifications. */
  QueueTimeOutURL: string;

  /** Public HTTPS endpoint for final transaction results. */
  ResultURL: string;

  /**
   * Optional additional transaction description.
   * IMPORTANT: Safaricom spells this field "Occassion".
   */
  Occassion?: string;
}
