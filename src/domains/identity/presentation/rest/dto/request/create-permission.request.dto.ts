// Exported Constants
// -----------------------------------------------------------------------------

export {
  MIN_NAME_LENGTH as PERMISSION_CREATE_NAME_MIN_LENGTH,
  MAX_NAME_LENGTH as PERMISSION_CREATE_NAME_MAX_LENGTH,
  MIN_CODE_LENGTH as PERMISSION_CREATE_CODE_MIN_LENGTH,
  MAX_CODE_LENGTH as PERMISSION_CREATE_CODE_MAX_LENGTH,
  MIN_RESOURCE_LENGTH as PERMISSION_CREATE_RESOURCE_MIN_LENGTH,
  MAX_RESOURCE_LENGTH as PERMISSION_CREATE_RESOURCE_MAX_LENGTH,
  MIN_ACTION_LENGTH as PERMISSION_CREATE_ACTION_MIN_LENGTH,
  MAX_ACTION_LENGTH as PERMISSION_CREATE_ACTION_MAX_LENGTH,
  MIN_DESCRIPTION_LENGTH as PERMISSION_CREATE_DESCRIPTION_MIN_LENGTH,
  MAX_DESCRIPTION_LENGTH as PERMISSION_CREATE_DESCRIPTION_MAX_LENGTH,
  MIN_CORRELATION_ID_LENGTH as PERMISSION_CREATE_CORRELATION_ID_MIN_LENGTH,
  MAX_CORRELATION_ID_LENGTH as PERMISSION_CREATE_CORRELATION_ID_MAX_LENGTH,
  MIN_CAUSATION_ID_LENGTH as PERMISSION_CREATE_CAUSATION_ID_MIN_LENGTH,
  MAX_CAUSATION_ID_LENGTH as PERMISSION_CREATE_CAUSATION_ID_MAX_LENGTH,
};
