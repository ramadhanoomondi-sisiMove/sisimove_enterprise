// -----------------------------------------------------------------------------
// Financial Account Hold — Cancel Request DTO
// -----------------------------------------------------------------------------
//
// REST request DTO for cancelling a Financial Account Hold.
//
// Lifecycle transition:
//
//     ACTIVE -> CANCELLED
//
// The hold identifier is supplied through the URL:
//
//     POST /financial-account-holds/:holdPublicId/cancel
//
// The controller generates the correlation ID for the cancellation command.
//
// This DTO performs transport-level validation only.
//
// Domain lifecycle rules remain inside:
// - FinancialAccountHoldAggregate;
// - FinancialAccountHoldEntity.
//
// The DTO does NOT:
// - Resolve the Financial Account Hold;
// - Validate aggregate lifecycle rules;
// - Execute a RELEASE transaction;
// - Modify Financial Account balances;
// - Move money.
//
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------
// NestJS Swagger
// -----------------------------------------------------------------------------

import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

// -----------------------------------------------------------------------------
// Class Transformer
// -----------------------------------------------------------------------------

import { Transform, type TransformFnParams } from 'class-transformer';

// -----------------------------------------------------------------------------
// Class Validator
// -----------------------------------------------------------------------------

import {
  IsDateString,
  IsOptional,
  IsString,
  Matches,
  MaxLength,
  MinLength,
} from 'class-validator';

// -----------------------------------------------------------------------------
// Helpers
// -----------------------------------------------------------------------------

const trimString = ({ value }: TransformFnParams): unknown =>
  typeof value === 'string' ? value.trim() : value;

// -----------------------------------------------------------------------------
// DTO
// -----------------------------------------------------------------------------

/**
 * REST request DTO for cancelling a Financial Account Hold.
 *
 * Cancellation represents:
 *
 *     ACTIVE -> CANCELLED
 *
 * The hold public ID is supplied through the route parameter.
 * The correlation ID is generated by the controller.
 *
 * Cancellation requires a Financial RELEASE transaction because the
 * reserved funds must be resolved back to the Financial Account's available
 * balance.
 */
export class CancelFinancialAccountHoldRequestDto {
  // ===========================================================================
  // RELEASE Transaction Public ID
  // ===========================================================================

  @ApiProperty({
    example: 'FTX-WQC6Y7G',
    description:
      'Public identifier of the Financial RELEASE transaction that resolves the reserved funds.',
  })
  @Transform(trimString)
  @IsString()
  @MinLength(1)
  @MaxLength(128)
  @Matches(/^[A-Z0-9]+(?:-[A-Z0-9]+)+$/, {
    message:
      'releaseTransactionPublicId must be a valid Financial Transaction public identifier.',
  })
  releaseTransactionPublicId!: string;

  // ===========================================================================
  // Cancellation Timestamp
  // ===========================================================================

  @ApiProperty({
    example: '2026-08-25T08:30:00.000Z',
    description:
      'ISO-8601 timestamp at which the Financial Account Hold enters CANCELLED state.',
    format: 'date-time',
  })
  @Transform(trimString)
  @IsDateString(
    {},
    {
      message: 'cancelledAt must be a valid ISO 8601 date-time.',
    },
  )
  cancelledAt!: string;

  // ===========================================================================
  // Causation ID
  // ===========================================================================

  @ApiPropertyOptional({
    example: 'CMD-WQC6Y7G',
    description:
      'Optional identifier of the command or operation that caused this cancellation.',
    nullable: true,
  })
  @Transform(trimString)
  @IsOptional()
  @IsString()
  @MinLength(1)
  @MaxLength(128)
  causationId?: string;
}
