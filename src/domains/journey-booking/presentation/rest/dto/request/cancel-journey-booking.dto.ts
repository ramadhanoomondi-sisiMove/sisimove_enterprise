// -----------------------------------------------------------------------------
// Journey Booking — Cancel Request DTO
// -----------------------------------------------------------------------------

import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

import {
  IsDateString,
  IsEnum,
  IsOptional,
  IsString,
  MaxLength,
  MinLength,
} from 'class-validator';

import { JOURNEY_BOOKING_CANCELLATION_REASONS } from '../../../../domain/value-objects';

import type { JourneyBookingCancellationReasonValue } from '../../../../domain/value-objects';

// -----------------------------------------------------------------------------
// DTO
// -----------------------------------------------------------------------------

/**
 * Request payload for cancelling a Journey Booking.
 *
 * The booking public ID is supplied through the route parameter.
 * The acting user's identity is obtained from the authenticated request.
 * The correlation ID is generated by the controller.
 *
 * Only cancellation information that the requester needs to provide belongs
 * in this request body.
 */
export class CancelJourneyBookingDto {
  // ===========================================================================
  // Cancellation Reason
  // ===========================================================================

  @ApiProperty({
    description: 'Reason for cancelling the Journey Booking.',
    enum: JOURNEY_BOOKING_CANCELLATION_REASONS,
    example: 'PASSENGER_REQUEST',
  })
  @IsEnum(JOURNEY_BOOKING_CANCELLATION_REASONS)
  reason!: JourneyBookingCancellationReasonValue;

  // ===========================================================================
  // Reason Description
  // ===========================================================================

  @ApiPropertyOptional({
    description: 'Optional additional explanation for the cancellation.',
    example: 'Passenger changed travel plans.',
    maxLength: 1000,
  })
  @IsOptional()
  @IsString()
  @MinLength(1)
  @MaxLength(1000)
  reasonDescription?: string;

  // ===========================================================================
  // Cancellation Time
  // ===========================================================================

  @ApiPropertyOptional({
    description:
      'Explicit cancellation timestamp. When omitted, the application uses the current time.',
    example: '2026-08-18T14:30:00.000Z',
    format: 'date-time',
  })
  @IsOptional()
  @IsDateString()
  cancelledAt?: string;
}

// -----------------------------------------------------------------------------
// Default Export
// -----------------------------------------------------------------------------

export default CancelJourneyBookingDto;
